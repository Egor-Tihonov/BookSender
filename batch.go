// batch.go — накопление книг и таймер батча.
//
// Что делает:
//   - хранит список книг текущего батча в памяти (только file_id и имя,
//     сами файлы до отправки не качаем, диск на Koyeb стираемый);
//   - помнит unique_id уже отправленных книг, чтобы не слать дубли;
//   - при первой книге запускает таймер BATCH_WAIT (5 минут),
//     новые книги таймер не сбрасывают;
//   - по таймеру отдаёт весь список в mailer.go и очищает батч.
//
// Доступ к списку защищён sync.Mutex: вебхуки приходят параллельно.
//
// Зачем: книги уходят одним письмом, а не по одной.
